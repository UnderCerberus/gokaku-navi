import io
p = r'C:\Claude\gokaku-navi\js\english\syntax.js'
s = io.open(p, encoding='utf-8').read()

def rep(old, new, cnt=1):
    global s
    n = s.count(old)
    assert n == cnt, (n, old[:80])
    s = s.replace(old, new)

# The museum is closed on Mondays, so … → 月曜日は休みなので（既存の置換で、後ろの「ので・から・が」も活用させる。休みだので にしない）
rep(""".replace(/([月火水木金土日]曜日)に閉まっている/g, '$1は休みだ')""",
    """.replace(/([月火水木金土日]曜日)に閉まっている(ので|から|が|けれども)?/g, (m0, a0, b0) => a0 + 'は休み' + ({ 'ので': 'なので', 'から': 'だから', 'が': 'だが', 'けれども': 'だけれども' }[b0 || ''] || 'だ'))""")
rep(""".replace(/(博物館|美術館|図書館|店|レストラン|銀行|動物園|郵便局|水族館|病院)は(毎週)?([月火水木金土日]曜日)に閉まって(いる|いた)/g, (m0, a0, b0, c0, d0) => a0 + 'は' + c0 + 'は休み' + (d0 === 'いる' ? 'だ' : 'だった'))""",
    """.replace(/(博物館|美術館|図書館|店|レストラン|銀行|動物園|郵便局|水族館|病院)は(毎週)?([月火水木金土日]曜日)に閉まって(いる|いた)(ので|から|が|けれども)?/g, (m0, a0, b0, c0, d0, e0) => a0 + 'は' + c0 + 'は休み' + (d0 === 'いる' ? ({ 'ので': 'なので', 'から': 'だから', 'が': 'だが', 'けれども': 'だけれども' }[e0 || ''] || 'だ') : 'だった' + (e0 || '')))""")

io.open(p, 'w', encoding='utf-8', newline='\n').write(s)
print('ok')
